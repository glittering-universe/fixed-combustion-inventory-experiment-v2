def fmt(v):
    if isinstance(v, float):
        return repr(v)
    return str(v)

def build_factor_csv(rows, table_id, sector, out_name, gas_m3):
    """rows: (dept, fuel, tech, values[8], page). gas_m3: set of fuel names w/ g/m3 unit."""
    path = os.path.join(PARAM, out_name)
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["parameter_id", "sector", "department", "fuel", "combustion_technology",
                    "pollutant", "mode", "value", "unit", "capacity_condition",
                    "source_section", "physical_pdf_page"])
        for dept, fuel, tech, vals, page in rows:
            for pol, raw in zip(POLLUTANTS, vals):
                pid = f"{table_id}-{DEPT_CODE[dept]}-{FUEL_CODE[fuel]}-{TECH_CODE[tech]}-{pol}"
                if raw == "MB":
                    mode = "coal_sulfur_balance" if pol == "SO2" else "coal_particle_balance"
                    value, unit, cap = "", "", ""
                elif raw == "CAP":
                    mode = "capacity_lookup"
                    value, unit, cap = "", "g/kg燃料", CAP_COND
                else:
                    mode = "constant"
                    unit = "g/m3" if (fuel in gas_m3) else "g/kg燃料"
                    value, cap = fmt(raw), ""
                w.writerow([pid, sector, dept, fuel, tech, pol, mode, value, unit, cap,
                            f"附录{table_id} 表{table_id}.1" if table_id != "E" else "附录E 表E.7",
                            page])
    return path

